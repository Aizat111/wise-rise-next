export type Stats2 = {
  [row: string]: {
    [multiplier: number]: any[];
  };
};

export const initStats2 = (vallhala: number): Stats2 => {
  const stats: Stats2 = {};

  for (const row in MULTIPLIERS_VALUES['Low']) {
    stats[row] = {};

    if (!Array.isArray(MULTIPLIERS_VALUES['Low'][row][vallhala])) {
      continue;
    }

    MULTIPLIERS_VALUES['Low'][row][vallhala].forEach(multiplier => {
      stats[row][multiplier] = [];
    });

    if (vallhala > 0) stats[row][0] = [];
  }

  return stats;
};
